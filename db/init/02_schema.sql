-- Schema da aplicação. Executado como admin após 01_usuario_app.sh; os
-- privilégios padrão definidos lá concedem apenas DML ao usuário da aplicação.

CREATE TABLE cliente (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(120) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    telefone      VARCHAR(20),
    data_cadastro TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE produto (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120)  NOT NULL,
    descricao VARCHAR(500),
    preco     NUMERIC(10,2) NOT NULL CHECK (preco > 0),
    ativo     BOOLEAN       NOT NULL DEFAULT true
);

CREATE TABLE pedido (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  BIGINT        NOT NULL REFERENCES cliente(id),
    data_pedido TIMESTAMP     NOT NULL,
    status      VARCHAR(20)   NOT NULL CHECK (status IN ('PENDENTE','APROVADO','CANCELADO')),
    valor_total NUMERIC(12,2) NOT NULL CHECK (valor_total > 0)
);

CREATE TABLE item_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT        NOT NULL REFERENCES pedido(id),
    produto_id     BIGINT        NOT NULL REFERENCES produto(id),
    quantidade     INT           NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(10,2) NOT NULL CHECK (preco_unitario > 0)
);

-- Toda leitura de itens filtra por pedido_id. Sem este índice, cada consulta do
-- N+1 faria seq scan em ~300 mil linhas e a comparação LAZY x JOIN FETCH mediria
-- a falta de índice, não a quantidade de consultas.
CREATE INDEX idx_item_pedido_pedido ON item_pedido (pedido_id);

